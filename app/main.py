class SegmentEdits(BaseModel):
    tamil_text: str = Field(max_length=2500)


class EditPayload(BaseModel):
    segments: list[SegmentEdits] = Field(min_length=1, max_length=3000)


app = FastAPI(
    title="NammaDub",
    description="Local Japanese-to-Tamil video dubbing with real ASR, translation and voice cloning.",
    version="1.0.0",
)
STATIC_DIR = Path(__file__).parent / "static"
app.mount("/static", StaticFiles(directory=STATIC_DIR), name="static")

VIDEO_EXTENSIONS = {".mp4", ".mkv", ".mov", ".webm", ".avi", ".m4v"}
AUDIO_EXTENSIONS = {".wav", ".mp3", ".m4a", ".flac", ".ogg", ".aac", ".webm"}


def _ffmpeg_available() -> bool:
    return shutil.which("ffmpeg") is not None and shutil.which("ffprobe") is not None


def _save_upload(upload: UploadFile, destination: Path, limit_mb: int) -> int:
    destination.parent.mkdir(parents=True, exist_ok=True)
    total = 0
    limit = limit_mb * 1024 * 1024
    with destination.open("wb") as target:
        while True:
            chunk = upload.file.read(1024 * 1024)
            if not chunk:
                break
            total += len(chunk)
            if total > limit:
                target.close()
                destination.unlink(missing_ok=True)
                raise HTTPException(status_code=413, detail=f"File exceeds the {limit_mb} MB upload limit.")
            target.write(chunk)
    if total == 0:
        destination.unlink(missing_ok=True)
        raise HTTPException(status_code=400, detail="The uploaded file is empty.")
    return total


def _job_paths(job_id: str) -> tuple[Path, Path, Path]:
    # job_id is always generated by uuid4 in this process.
    folder = JOBS_DIR / job_id
    return folder, folder / "source_audio_16k.wav", folder / "dubbed_tamil.mp4"


def _public_status(job_id: str) -> dict:
    item = get_job(job_id)
    if item is None:
        raise HTTPException(status_code=404, detail="Job not found.")
    result = public_job(item)
    result["download_url"] = f"/api/jobs/{job_id}/download" if item.get("status") == "done" else None
    return result


def _process_transcription(job_id: str) -> None:
    item = get_job(job_id)
    if item is None:
        return
    folder, audio_path, _output = _job_paths(job_id)
    try:
        update_job(job_id, status="extracting", progress=5, message="Extracting audio from video…", error=None)
        extract_audio(Path(item["video_path"]), audio_path)
        update_job(job_id, status="transcribing", progress=12, message="Transcribing Japanese dialogue with Whisper…")
        segments = get_transcriber().transcribe(audio_path)
        update_job(job_id, progress=42, message="Detecting speakers…")
        segments = assign_speakers(audio_path, segments, bool(item.get("diarization")))
        update_job(job_id, progress=48, message="Translating Japanese dialogue into conversational Tamil…")
        translator, engine_name = make_translator(item.get("translator", "auto"))
        for index, segment in enumerate(segments):
            segment.tamil_text = translator.translate(segment.source_text)
            progress = 48 + int(37 * (index + 1) / max(1, len(segments)))
            update_job(
                job_id,
                progress=progress,
                message=f"Translating dialogue ({index + 1}/{len(segments)})…",
            )
        save_segments(folder / "segments.json", segments)
        update_job(
            job_id,
            status="ready_for_review",
            progress=88,
            message="Review and edit the Tamil lines, then create the dubbed video.",
            segments=[segment.to_dict() for segment in segments],
            translation_engine=engine_name,
            speakers=sorted({segment.speaker_id for segment in segments}),
        )
    except Exception as exc:
        update_job(job_id, status="failed", error=str(exc), message="Transcription/translation failed.")


def _render_job(job_id: str) -> None:
    item = get_job(job_id)
    if item is None:
        return
    folder, audio_path, output_path = _job_paths(job_id)
    try:
        segments_path = folder / "segments.json"
        segments = load_segments(segments_path)
        update_job(job_id, status="preparing_voice", progress=8, message="Preparing voice references…")
        uploaded_reference = Path(item["reference_path"]) if item.get("reference_path") else None
        reference_map = ensure_references(
            audio_path,
            segments,
            folder,
            uploaded_reference,
            item.get("reference_text", ""),
        )
        update_job(job_id, status="rendering", progress=20, message="Loading IndicF5 Tamil voice-cloning model…")
        cloner = get_voice_cloner()

        def on_progress(progress: int, message: str) -> None:
            update_job(job_id, progress=progress, message=message)

        render_dub(
            Path(item["video_path"]),
            audio_path,
            segments,
            reference_map,
            cloner,
            folder,
            output_path,
            bool(item.get("preserve_background", True)),
            on_progress,
        )
        update_job(
            job_id,
            status="done",
            progress=100,
            message="Your Tamil dubbed video is ready.",
            output_name=output_path.name,
            error=None,
        )
    except Exception as exc:
        update_job(job_id, status="failed", error=str(exc), message="Tamil voice generation/rendering failed.")


