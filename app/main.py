@app.get("/api/health")
def health() -> dict:
    ollama_ok = False
    try:
        import requests
        response = requests.get(f"{OLLAMA_URL}/api/tags", timeout=(0.5, 0.8))
        ollama_ok = response.ok
    except Exception:
        pass
    return {
        "ok": _ffmpeg_available(),
        "ffmpeg": _ffmpeg_available(),
        "huggingface_token_present": bool(HF_TOKEN),
        "ollama_available": ollama_ok,
        "max_video_minutes": MAX_VIDEO_MINUTES,
        "max_upload_mb": MAX_UPLOAD_MB,
        "translation_default": "Ollama when available, otherwise NLLB-200",
        "voice_model": "ai4bharat/IndicF5",
    }


@app.post("/api/jobs", status_code=202)
async def create_job(
    background_tasks: BackgroundTasks,
    video: Annotated[UploadFile, File(...)],
    voice_source: Annotated[str, Form()] = "video",
    reference_audio: Annotated[UploadFile | None, File()] = None,
    reference_text: Annotated[str, Form()] = "",
    translator: Annotated[str, Form()] = "auto",
    diarization: Annotated[bool, Form()] = False,
    preserve_background: Annotated[bool, Form()] = True,
    voice_consent: Annotated[bool, Form()] = False,
):
    if not _ffmpeg_available():
        raise HTTPException(status_code=500, detail="FFmpeg and ffprobe are required. Install FFmpeg and restart NammaDub.")
    if not voice_consent:
        raise HTTPException(status_code=400, detail="Confirm that you own or have permission to clone the reference voice.")
    if voice_source not in {"video", "upload"}:
        raise HTTPException(status_code=400, detail="voice_source must be video or upload")
    if translator not in {"auto", "ollama", "nllb"}:
        raise HTTPException(status_code=400, detail="translator must be auto, ollama, or nllb")
    video_suffix = Path(video.filename or "video.mp4").suffix.lower()
    if video_suffix not in VIDEO_EXTENSIONS:
        raise HTTPException(status_code=400, detail="Use an MP4, MKV, MOV, WebM, AVI or M4V video file.")
    if voice_source == "upload":
        if reference_audio is None:
            raise HTTPException(status_code=400, detail="Upload a 4-30 second voice reference file.")
        if not reference_text.strip():
            raise HTTPException(status_code=400, detail="Enter the exact transcript spoken in the voice reference.")
    if voice_source == "video" and reference_audio is not None:
        raise HTTPException(status_code=400, detail="Choose 'uploaded reference' or 'extract voice from video', not both.")

    job_id = uuid.uuid4().hex
    folder, _audio, _output = _job_paths(job_id)
    folder.mkdir(parents=True, exist_ok=True)
    video_path = folder / f"source{video_suffix}"
    await asyncio.to_thread(_save_upload, video, video_path, MAX_UPLOAD_MB)
    try:
        duration = await asyncio.to_thread(probe_duration, video_path)
    except Exception as exc:
        shutil.rmtree(folder, ignore_errors=True)
        raise HTTPException(status_code=400, detail=f"Could not read the uploaded video: {exc}") from exc
    if duration > MAX_VIDEO_MINUTES * 60:
        shutil.rmtree(folder, ignore_errors=True)
        raise HTTPException(
            status_code=413,
            detail=f"Video is {duration / 60:.1f} minutes. The limit is {MAX_VIDEO_MINUTES} minutes.",
        )

    reference_path = None
    if reference_audio is not None:
        audio_suffix = Path(reference_audio.filename or "reference.wav").suffix.lower()
        if audio_suffix not in AUDIO_EXTENSIONS:
            shutil.rmtree(folder, ignore_errors=True)
            raise HTTPException(status_code=400, detail="Unsupported reference audio format.")
        reference_path = folder / f"voice_reference_upload{audio_suffix}"
        await asyncio.to_thread(_save_upload, reference_audio, reference_path, MAX_REFERENCE_MB)

    put_job(job_id, {
        "id": job_id,
        "status": "queued",
        "progress": 1,
        "message": "Job queued…",
        "duration_seconds": duration,
        "translator": translator,
        "translation_engine": None,
        "voice_source": voice_source,
        "reference_path": str(reference_path) if reference_path else None,
        "reference_text": reference_text.strip(),
        "diarization": diarization,
        "preserve_background": preserve_background,
        "video_path": str(video_path),
        "job_dir": str(folder),
        "segments": [],
        "speakers": [],
        "error": None,
    })
    background_tasks.add_task(_process_transcription, job_id)
    return _public_status(job_id)


@app.get("/api/jobs/{job_id}")
def job_status(job_id: str) -> dict:
    return _public_status(job_id)


@app.put("/api/jobs/{job_id}/segments")
def edit_segments(job_id: str, payload: EditPayload) -> dict:
    item = get_job(job_id)
    if item is None:
        raise HTTPException(status_code=404, detail="Job not found.")
    if item.get("status") != "ready_for_review":
        raise HTTPException(status_code=409, detail="Tamil lines can only be edited after translation is complete.")
    current = load_segments(Path(item["job_dir"]) / "segments.json")
    if len(payload.segments) != len(current):
        raise HTTPException(status_code=400, detail="The number of edited lines does not match the transcript.")
    for segment, edit in zip(current, payload.segments):
        segment.tamil_text = edit.tamil_text.strip()
    save_segments(Path(item["job_dir"]) / "segments.json", current)
    update_job(job_id, segments=[segment.to_dict() for segment in current])
    return {"ok": True, "edited_lines": len(current)}


@app.post("/api/jobs/{job_id}/render", status_code=202)
def start_render(job_id: str, background_tasks: BackgroundTasks) -> dict:
    item = get_job(job_id)
    if item is None:
        raise HTTPException(status_code=404, detail="Job not found.")
    if item.get("status") != "ready_for_review":
        raise HTTPException(status_code=409, detail="Wait until Japanese transcription and Tamil translation are ready.")
    segments = load_segments(Path(item["job_dir"]) / "segments.json")
    if not any(segment.tamil_text.strip() for segment in segments):
        raise HTTPException(status_code=400, detail="At least one Tamil line is required.")
    update_job(job_id, status="preparing_voice", progress=2, message="Render queued…", error=None)
    background_tasks.add_task(_render_job, job_id)
    return _public_status(job_id)


@app.get("/api/jobs/{job_id}/download")
def download_job(job_id: str) -> FileResponse:
    item = get_job(job_id)
    if item is None:
        raise HTTPException(status_code=404, detail="Job not found.")
    if item.get("status") != "done":
        raise HTTPException(status_code=409, detail="The dubbed video is not ready yet.")
    output_path = Path(item["job_dir"]) / "dubbed_tamil.mp4"
    if not output_path.is_file():
        raise HTTPException(status_code=404, detail="Dubbed output file is missing.")
    return FileResponse(
        output_path,
        media_type="video/mp4",
        filename=f"namma-dub-{job_id[:8]}.mp4",
    )
